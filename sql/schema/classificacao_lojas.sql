-- Colunas do CASE original de classificacao comercial das lojas.
-- Inclusao idempotente; converte flags antigos 'S' para 1 e tipo INT.
-- Preserva NULL, as cinco ILHA_V2 e os demais dados ja preenchidos.
USE DATALAKE;
SET NOCOUNT ON;
SET XACT_ABORT ON;

BEGIN TRY
BEGIN TRANSACTION;

IF OBJECT_ID(N'dbo.DL_BRADESCO_EXPRESSO', N'U') IS NULL
    THROW 50001, 'Tabela DATALAKE.dbo.DL_BRADESCO_EXPRESSO nao encontrada.', 1;

IF COL_LENGTH(N'dbo.DL_BRADESCO_EXPRESSO', N'ILHA_V2') IS NULL
    ALTER TABLE dbo.DL_BRADESCO_EXPRESSO ADD ILHA_V2 INT NULL;

IF COL_LENGTH(N'dbo.DL_BRADESCO_EXPRESSO', N'BE_ILHA') IS NULL
    ALTER TABLE dbo.DL_BRADESCO_EXPRESSO ADD BE_ILHA INT NULL;

IF COL_LENGTH(N'dbo.DL_BRADESCO_EXPRESSO', N'BE_EXCLUSIVO') IS NULL
    ALTER TABLE dbo.DL_BRADESCO_EXPRESSO ADD BE_EXCLUSIVO INT NULL;

IF COL_LENGTH(N'dbo.DL_BRADESCO_EXPRESSO', N'COD_GRUPO_ECON') IS NULL
    ALTER TABLE dbo.DL_BRADESCO_EXPRESSO ADD COD_GRUPO_ECON INT NULL;

IF COL_LENGTH(N'dbo.DL_BRADESCO_EXPRESSO', N'DESC_GERENCIA_NEGOCIO') IS NULL
    ALTER TABLE dbo.DL_BRADESCO_EXPRESSO ADD DESC_GERENCIA_NEGOCIO VARCHAR(255) NULL;

IF EXISTS (
    SELECT 1 FROM sys.columns
    WHERE object_id = OBJECT_ID(N'dbo.DL_BRADESCO_EXPRESSO')
      AND name = N'BE_ILHA' AND system_type_id <> TYPE_ID(N'int')
)
BEGIN
    EXEC sys.sp_executesql N'
        UPDATE dbo.DL_BRADESCO_EXPRESSO SET BE_ILHA = ''1''
        WHERE CONVERT(VARCHAR(20), BE_ILHA) = ''S'';';
    ALTER TABLE dbo.DL_BRADESCO_EXPRESSO ALTER COLUMN BE_ILHA INT NULL;
END;

IF EXISTS (
    SELECT 1 FROM sys.columns
    WHERE object_id = OBJECT_ID(N'dbo.DL_BRADESCO_EXPRESSO')
      AND name = N'BE_EXCLUSIVO' AND system_type_id <> TYPE_ID(N'int')
)
BEGIN
    EXEC sys.sp_executesql N'
        UPDATE dbo.DL_BRADESCO_EXPRESSO SET BE_EXCLUSIVO = ''1''
        WHERE CONVERT(VARCHAR(20), BE_EXCLUSIVO) = ''S'';';
    ALTER TABLE dbo.DL_BRADESCO_EXPRESSO ALTER COLUMN BE_EXCLUSIVO INT NULL;
END;

COMMIT TRANSACTION;
END TRY
BEGIN CATCH
    IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;
    THROW;
END CATCH;
