SELECT TOP (5000)
    CAST(P.DATA_TRX AS DATE)        AS DIA,
    P.INDICADOR,
    P.SITUACAO_CONTRATO_CONSOLIDADO AS SITUACAO,
    P.CONTRATO,
    P.NSU_TRX,
    P.CPF_CLIENTE,
    P.VLR_CONTRATO,
    CASE
        WHEN P.SITUACAO_CONTRATO_CONSOLIDADO IN ('AGUARDANDO AVERBACAO', 'NAO AVERBADO')
        THEN DP.msg_retorno_dataprev
    END AS MOTIVO_DATAPREV
FROM DEF..TB_CONSIG_AVERBADO_EXP P
OUTER APPLY (
    SELECT TOP (1) D.msg_retorno_dataprev
    FROM DEF..TB_CONSIG_DATAPREV D
    WHERE D.contrato = CAST(P.CONTRATO AS VARCHAR(30))
    ORDER BY D.ultima_atualizacao DESC
) DP
WHERE P.CHAVE_LOJA = ?
  AND P.DATA_TRX >= CAST(? AS DATE)
  AND P.DATA_TRX < DATEADD(DAY, 1, CAST(? AS DATE))
  /*PRODUTO*/
  /*SITUACAO*/
ORDER BY P.DATA_TRX DESC, P.VLR_CONTRATO DESC;
