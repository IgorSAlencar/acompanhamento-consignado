WITH LOJAS AS (
    SELECT DISTINCT
        A.CHAVE_LOJA /*COLUNA_SEGMENTO*/,
        LTRIM(RTRIM(A.NOME_LOJA)) AS NOME_LOJA,
        H.DESC_GERENCIA_AREA,
        H.DESC_COORDENACAO,
        H.DESC_SUPERVISAO
    FROM DATALAKE..DL_BRADESCO_EXPRESSO A
    /*JOIN_HIERARQUIA*/ MESU..CONS_DISTRIBUICAO_ENTIDADES H
        ON TRY_CAST(H.COD_AG AS BIGINT) = A.COD_AG_LOJA
    WHERE CASE
              WHEN A.ILHA_V2 > 0 THEN 'Ilha 2.0'
              WHEN A.BE_ILHA > 0 THEN 'Ilha'
              WHEN A.BE_EXCLUSIVO > '0' THEN 'Exclusivo'
              WHEN A.COD_GRUPO_ECON IN (36, 202) THEN 'Casas Bahia'
              WHEN A.DESC_GERENCIA_NEGOCIO IS NOT NULL THEN 'Grandes Redes'
              ELSE 'Varejo'
          END /*UNIVERSO*/
      /*FILTROS*/
)
SELECT
    L.SEGMENTO,
    L.DESC_GERENCIA_AREA,
    L.DESC_COORDENACAO,
    L.DESC_SUPERVISAO,
    L.CHAVE_LOJA,
    L.NOME_LOJA,
    T.PRODUTO,
    CAST(T.DATA_ETAPA AS DATE)  AS DATA_ETAPA,
    ISNULL(SUM(T.QTD_CLIENTES), 0) AS QTD_CLIENTES,
    SUM(T.QTD_CONVERTIDAS)      AS QTD_CONVERTIDOS,
    SUM(T.QTD_ABANDONADAS)      AS QTD_ABANDONADAS,
    SUM(T.QTD_ERRO_INELEGIBILIDADE) AS QTD_ERRO_INELEGIBILIDADE,
    SUM(ISNULL(T.QTD_OUTROS_ERROS, 0)) AS QTD_OUTROS_ERROS
FROM TESTE..TENTATIVAS_CONSIGNADO_DIA T
INNER JOIN LOJAS L ON L.CHAVE_LOJA = T.CHAVE_LOJA
WHERE T.DATA_ETAPA >= CAST(? AS DATE)
  AND T.DATA_ETAPA < DATEADD(DAY, 1, CAST(? AS DATE))
  /*PRODUTO*/
GROUP BY
    L.SEGMENTO,
    L.DESC_GERENCIA_AREA,
    L.DESC_COORDENACAO,
    L.DESC_SUPERVISAO,
    L.CHAVE_LOJA,
    L.NOME_LOJA,
    T.PRODUTO,
    CAST(T.DATA_ETAPA AS DATE)
ORDER BY CAST(T.DATA_ETAPA AS DATE) DESC, L.NOME_LOJA, T.PRODUTO;
