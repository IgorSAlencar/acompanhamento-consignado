WITH LOJAS AS (
    SELECT DISTINCT
        A.CHAVE_LOJA /*COLUNA_SEGMENTO*/,
        LTRIM(RTRIM(A.NOME_LOJA)) AS NOME_LOJA,
        H.DESC_GERENCIA_AREA,
        H.DESC_COORDENACAO,
        H.DESC_SUPERVISAO
    FROM DATALAKE..DL_BRADESCO_EXPRESSO A
    /*JOIN_HIERARQUIA*/ MESU..CONS_DISTRIBUICAO_ENTIDADES H
        ON TRY_CAST(H.COD_AG AS BIGINT) = A.COD_AG_LOJA
    WHERE CASE
              WHEN A.ILHA_V2 > 0 THEN 'Ilha 2.0'
              WHEN A.BE_ILHA > 0 THEN 'Ilha'
              WHEN A.BE_EXCLUSIVO > '0' THEN 'Exclusivo'
              WHEN A.COD_GRUPO_ECON IN (36, 202) THEN 'Casas Bahia'
              WHEN A.DESC_GERENCIA_NEGOCIO IS NOT NULL THEN 'Grandes Redes'
              ELSE 'Varejo'
          END /*UNIVERSO*/
      /*FILTROS*/
)
SELECT
    L.SEGMENTO,
    L.DESC_GERENCIA_AREA,
    L.DESC_COORDENACAO,
    L.DESC_SUPERVISAO,
    L.CHAVE_LOJA,
    L.NOME_LOJA,
    CAST(P.DATA_TRX AS DATE)        AS DIA,
    P.INDICADOR,
    P.SITUACAO_CONTRATO_CONSOLIDADO AS SITUACAO,
    P.CONTRATO,
    P.NSU_TRX,
    P.CPF_CLIENTE,
    P.VLR_CONTRATO,
    CASE
        WHEN P.SITUACAO_CONTRATO_CONSOLIDADO IN ('AGUARDANDO AVERBACAO', 'NAO AVERBADO')
        THEN DP.msg_retorno_dataprev
    END AS MOTIVO_DATAPREV
FROM DEF..TB_CONSIG_AVERBADO_EXP P
OUTER APPLY (
    SELECT TOP (1) D.msg_retorno_dataprev
    FROM DEF..TB_CONSIG_DATAPREV D
    WHERE D.contrato = CAST(P.CONTRATO AS VARCHAR(30))
    ORDER BY D.ultima_atualizacao DESC
) DP
INNER JOIN LOJAS L ON L.CHAVE_LOJA = P.CHAVE_LOJA
WHERE P.DATA_TRX >= CAST(? AS DATE)
  AND P.DATA_TRX < DATEADD(DAY, 1, CAST(? AS DATE))
  /*PRODUTO*/
  /*SITUACAO*/
ORDER BY P.DATA_TRX DESC, P.VLR_CONTRATO DESC;
